/**
 * The field dictionary.
 *
 * One entry per *meaning*, not per widget. `contact.phone` covers 手机号码,
 * Mobile Number, 联系电话 and 联系方式手机; the classifier's job is to map a
 * messy label onto one of these.
 *
 * Fields are ordered by the sequence in which they usually appear on Chinese
 * campus-recruitment forms, and `priority` drives how much we care when we
 * could not find a value.
 */

import type { FieldKind, FieldSection } from "../types.js";

export interface FieldDefinition {
  /** Canonical dotted key. Also the memory key. */
  key: string;
  /** Short Chinese label used in the UI. */
  label: string;
  /** English label for ARIA output and the English UI. */
  labelEn: string;
  section: FieldSection;
  /** Normalised aliases. Both languages, all the variants we have seen. */
  aliases: string[];
  /** If any of these appear, the field is *not* this key. */
  excludes?: string[];
  /** Acceptable widget kinds; empty means "anything". */
  kinds?: FieldKind[];
  /** 0-100 — how bad is it to leave this empty? */
  priority: number;
  /** Written into a `<select>`/radio when nothing better is available. */
  hints?: string;
}

