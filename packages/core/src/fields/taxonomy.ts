/** Fast lookup by canonical key. */
export const DEFINITION_BY_KEY: Map<string, FieldDefinition> = new Map(
  FIELD_DEFINITIONS.map((definition) => [definition.key, definition]),
);

/** Which section a key belongs to, without needing the full definition. */
export function sectionOfKey(key: string | undefined): FieldSection {
  if (!key) return "unknown";
  const definition = DEFINITION_BY_KEY.get(key);
  if (definition) return definition.section;
  const prefix = key.split(".")[0];
  switch (prefix) {
    case "identity":
    case "contact":
    case "education":
    case "work":
    case "project":
    case "skill":
    case "preference":
    case "essay":
    case "meta":
      return prefix === "work" ? "experience" : (prefix as FieldSection);
    default:
      return "unknown";
  }
}

